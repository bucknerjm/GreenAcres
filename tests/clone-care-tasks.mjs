import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {DatabaseSync} from 'node:sqlite';
import vm from 'node:vm';
const source=readFileSync(new URL('../worker.js',import.meta.url),'utf8');
const ctx=vm.createContext({console,TextEncoder,TextDecoder,crypto,Response,Headers,Request,URL});
vm.runInContext(source.split('const dashboardAssets=')[0]+';globalThis.api={hasActiveClones,cloneCareVisible,cloneCareTitle};',ctx);
const sql=new DatabaseSync(':memory:');
const db={prepare(query){return {bind(...args){return {async first(){return sql.prepare(query).get(...args)||null;},async all(){return {results:sql.prepare(query).all(...args)};},async run(){return sql.prepare(query).run(...args);}};},async run(){return sql.prepare(query).run();}};},async batch(stmts){return Promise.all(stmts.map(s=>s.run()));}};
const {hasActiveClones,cloneCareVisible,cloneCareTitle}=ctx.api;
assert.equal(await hasActiveClones(db),false);
sql.prepare('INSERT INTO clone_position_layouts(id,assignments_json) VALUES(?,?)').run('rack:2:1','{"A1":"Toad Venom"}');
assert.equal(await hasActiveClones(db),true);
sql.exec("UPDATE clone_crop_groups SET status='finished'; INSERT INTO clone_crop_groups(id,crop_id,label,storage_prefix) VALUES('next','north-37','North Crop 37','next:');");
assert.equal(await hasActiveClones(db),false,'archived occupied trays do not keep task active');
sql.prepare('INSERT INTO clone_position_layouts(id,assignments_json) VALUES(?,?)').run('next:rack:2:1','{"A1":""}');
assert.equal(await hasActiveClones(db),false);
sql.exec(`UPDATE clone_position_layouts SET assignments_json='{"A1":"Gasface"}' WHERE id='next:rack:2:1'`);
assert.equal(await hasActiveClones(db),true,'new group planting resumes care');
const task={title:cloneCareTitle,template_id:'clones',status:'open'};
assert.equal(cloneCareVisible(task,false),false);
assert.equal(cloneCareVisible(task,true),true);
assert.equal(cloneCareVisible({...task,status:'completed'},false),true);
assert.equal(cloneCareVisible({...task,title:'Mix nutrients'},false),true);
assert.equal(cloneCareVisible({...task,template_id:null},false),true);
console.log('PASS: empty/occupied/new/archived racks and completed clone-care history.');
